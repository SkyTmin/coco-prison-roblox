// Bundles a location built from parts into one Studio script:
//   scripts/locations/<id>/00-header.luau  (LOC, ROOT_NAME, BX, BY, BZ, SEED)
//   scripts/locations/kit.luau             (the shared block kit)
//   scripts/locations/<id>/NN-*.luau       (the plan and the parts, in name order, each wrapped in do … end)
// → scripts/build-<id>.luau, run in Studio (Edit) via scripts/studio-loader.luau after build-textures.
// node scripts/bundle-location.mjs market
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const id = process.argv[2];
if (!id) {
	console.error("usage: node scripts/bundle-location.mjs <location id>");
	process.exit(1);
}
const dir = path.join(ROOT, "scripts", "locations", id);
const files = fs.readdirSync(dir).filter((f) => f.endsWith(".luau")).sort();
const header = files.find((f) => f.startsWith("00-"));
if (!header) {
	console.error(`no 00-header.luau in ${dir}`);
	process.exit(1);
}
const read = (p) => fs.readFileSync(p, "utf8").replace(/^--!nocheck\r?\n/, "");
const out = ["--!nocheck", `-- GENERATED by node scripts/bundle-location.mjs ${id} — edit scripts/locations/${id}/*.luau and kit.luau, not this file.`];
out.push(read(path.join(dir, header)));
out.push("-- ================================================================================ kit.luau");
out.push(read(path.join(ROOT, "scripts", "locations", "kit.luau")));
for (const f of files) {
	if (f === header) continue;
	const body = read(path.join(dir, f));
	// the plan (05-*) shares locals with every part, so it is not wrapped; parts are, to keep the local count low
	const shared = f.startsWith("05-");
	out.push(`-- ================================================================================ ${id}/${f}`);
	out.push(shared ? body : `do\n${body}\nend\ntask.wait()`);
}
out.push(`local total = #root:GetDescendants()`);
out.push(`print(("[build-${id}] built: %d instances, %d parts"):format(total, count))`);
out.push(`return ("built %d instances, %d parts"):format(total, count)`);
const target = path.join(ROOT, "scripts", `build-${id.replace(/_/g, "-")}.luau`);
fs.writeFileSync(target, out.join("\n") + "\n");
console.log(`${path.relative(ROOT, target)}: ${files.length} parts, ${out.join("\n").split("\n").length} lines`);
