#!/usr/bin/env python3
"""Generates plugin/Font.luau: an anti-aliased bitmap font (DejaVu Sans Bold) for the relay's
software renderer. Each glyph = alpha 0..15 per pixel as one hex char. Usage: python3 gen-font.py"""
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

SIZE = 13
FONT = "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf"
chars = [chr(c) for c in range(32, 127)]
chars += [chr(c) for c in range(0x410, 0x450)] + ["Ё", "ё"]
chars += list("«»—–…№×·•✓✔→←↑↓★☆♥°₽€✕✖⚔⏱⚡")
font = ImageFont.truetype(FONT, SIZE)
ascent, descent = font.getmetrics()
line = ascent + descent
out = []
for ch in chars:
    adv = max(1, round(font.getlength(ch)))
    bbox = font.getbbox(ch)
    if ch == " " or bbox[2] <= bbox[0]:
        out.append((ord(ch), 0, adv, 0, 0, 0, ""))
        continue
    x0, y0, x1, y1 = bbox
    w, h = x1 - x0, y1 - y0
    img = Image.new("L", (w, h), 0)
    ImageDraw.Draw(img).text((-x0, -y0), ch, font=font, fill=255)
    px = img.load()
    hexs = "".join("%x" % (px[x, y] * 15 // 255) for y in range(h) for x in range(w))
    if hexs.strip("0") == "":
        out.append((ord(ch), 0, adv, 0, 0, 0, ""))
        continue
    out.append((ord(ch), w, adv, x0, y0, h, hexs))
lines = [
    "--!nocheck",
    "-- GENERATED by tools/studio-relay/scripts/gen-font.py (DejaVu Sans Bold %d px). Do not edit." % SIZE,
    "-- glyph = { w, advance, xoff, yoff, h, alpha hex (0..f per pixel, row-major) }",
    "return {",
    "\tsize = %d," % SIZE,
    "\tascent = %d," % ascent,
    "\tline = %d," % line,
    "\tglyphs = {",
]
for cp, w, adv, x0, y0, h, hexs in out:
    lines.append('\t\t[%d] = { %d, %d, %d, %d, %d, "%s" },' % (cp, w, adv, x0, y0, h, hexs))
lines += ["\t},", "}", ""]
p = Path(__file__).resolve().parent.parent / "plugin" / "Font.luau"
p.write_text("\n".join(lines), encoding="utf-8")
print(p, len(out), "glyphs", p.stat().st_size, "bytes")
