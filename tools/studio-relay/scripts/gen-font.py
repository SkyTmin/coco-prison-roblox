#!/usr/bin/env python3
"""Generates plugin/Font.luau: an anti-aliased bitmap font (DejaVu Sans Bold) for the relay's
software renderer. Each glyph = alpha 0..15 per pixel as one hex char. Usage: python3 gen-font.py"""
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

SIZES = [9, 12, 16, 22, 30]
FONT = "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf"
chars = [chr(c) for c in range(32, 127)]
chars += [chr(c) for c in range(0x410, 0x450)] + ["Ё", "ё"]
chars += list("«»—–…№×·•✓✔→←↑↓★☆♥°₽€✕✖⚔⏱⚡")
def rle(raw):
    # zeros are packed: g..z = a run of 1..20 zeros; 1..f stay literal alpha
    out, i = [], 0
    while i < len(raw):
        if raw[i] == "0":
            j = i
            while j < len(raw) and raw[j] == "0" and j - i < 20:
                j += 1
            out.append(chr(ord("g") + (j - i) - 1))
            i = j
        else:
            out.append(raw[i])
            i += 1
    return "".join(out)


def build(size):
    font = ImageFont.truetype(FONT, size)
    ascent, descent = font.getmetrics()
    out = []
    for ch in chars:
        adv = max(1, round(font.getlength(ch)))
        bbox = font.getbbox(ch)
        if ch == " " or bbox[2] <= bbox[0]:
            out.append((ord(ch), 0, adv, 0, 0, 0, ""))
            continue
        x0, y0, x1, y1 = bbox
        w, h = x1 - x0, y1 - y0
        img = Image.new("L", (w, h), 0)
        ImageDraw.Draw(img).text((-x0, -y0), ch, font=font, fill=255)
        px = img.load()
        raw = "".join("%x" % (px[x, y] * 15 // 255) for y in range(h) for x in range(w))
        hexs = rle(raw)
        if raw.strip("0") == "":
            out.append((ord(ch), 0, adv, 0, 0, 0, ""))
            continue
        out.append((ord(ch), w, adv, x0, y0, h, hexs))
    return ascent, ascent + descent, out


lines = [
    "--!nocheck",
    "-- GENERATED by tools/studio-relay/scripts/gen-font.py (DejaVu Sans Bold). Do not edit.",
    "-- sizes[i] = { size, ascent, line, glyphs }; glyph = { w, advance, xoff, yoff, h, alpha: 1..f literal, g..z = 1..20 zeros }",
    "return {",
]
for size in SIZES:
    ascent, line, out = build(size)
    lines.append("\t{")
    lines.append("\t\tsize = %d," % size)
    lines.append("\t\tascent = %d," % ascent)
    lines.append("\t\tline = %d," % line)
    lines.append("\t\tglyphs = {")
    for cp, w, adv, x0, y0, h, hexs in out:
        lines.append('\t\t\t[%d] = { %d, %d, %d, %d, %d, "%s" },' % (cp, w, adv, x0, y0, h, hexs))
    lines.append("\t\t},")
    lines.append("\t},")
lines += ["}", ""]
p = Path(__file__).resolve().parent.parent / "plugin" / "Font.luau"
p.write_text("\n".join(lines), encoding="utf-8")
print(p, len(SIZES), "sizes", p.stat().st_size, "bytes")
